"""Compare QLever per-country results with the earlier WDQS cache.

sample_people.py switched from WDQS (query.wikidata.org) to QLever because WDQS timed
out on large countries. Before switching, the same per-country candidate query was run
on both endpoints for four citizenships -- Andorra (small), Bangladesh (mid-sized),
Argentina and France (large) -- and the results compared: people found by each source,
and, for people in both, agreement on sitelinks, English description, citizenships and
birth date.

Inputs: data/raw/candidates/<QID>.csv (WDQS cache, 18 Nov 2026) and the QLever cache in
data/raw/candidates_qlever/ (fetched if missing). The WDQS cache has since been deleted,
so this script documents the check; its output is saved in docs/qlever_verification.md.
"""

from datetime import date

import pandas as pd

import sample_people as s

WDQS = s.ROOT / "data" / "raw" / "candidates"
OUT_PATH = s.ROOT / "docs" / "qlever_verification.md"
COUNTRIES = [("Q228", "Andorra (small)"), ("Q902", "Bangladesh (mid)"),
             ("Q414", "Argentina"), ("Q142", "France (large)")]


def per_person(df):
    g = df.groupby("person")
    return pd.DataFrame({"sitelinks": g["sitelinks"].max().astype(int),
                         "description": g["description"].max(),
                         "cit": g["cit"].agg(s.joined),
                         "birth": g["birth"].min().str[:10]})


def share(a, b):
    return f"{(a == b).mean():.1%}"


def markdown_table(df):
    lines = ["| " + " | ".join(df.columns) + " |",
             "|" + "|".join("---" for _ in df.columns) + "|"]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def main():
    index = s.snapshot_info()
    print(f"QLever index: {index}\n")
    rows = []
    for qid, name in COUNTRIES:
        w = per_person(pd.read_csv(WDQS / f"{qid}.csv", dtype=str, keep_default_na=False))
        q = per_person(pd.concat(s.fetch_range(qid, s.MIN_YEAR, s.MAX_YEAR)))
        both = w.index.intersection(q.index)
        wb, qb = w.loc[both], q.loc[both]
        rows.append({"country": f"{name} {qid}", "WDQS": len(w), "QLever": len(q),
                     "both": len(both), "WDQS only": len(w.index.difference(q.index)),
                     "QLever only": len(q.index.difference(w.index)),
                     "same sitelinks": share(wb["sitelinks"], qb["sitelinks"]),
                     "same descr.": share(wb["description"], qb["description"]),
                     "same cit.": share(wb["cit"], qb["cit"]),
                     "same birth": share(wb["birth"], qb["birth"])})
    table = pd.DataFrame(rows)
    print(table.to_string(index=False))

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(
        "# QLever vs WDQS verification\n\n"
        f"Generated by `src/verify_qlever.py` on {date.today().isoformat()}.\n\n"
        "Same per-country candidate query (humans, female/male, born 1900 or later, "
        "with an English Wikipedia article) run on both endpoints. WDQS results were "
        "fetched on 2026-11-18; QLever results come from its Wikidata index:\n\n"
        f"> {index}\n\n"
        + markdown_table(table) + "\n\n"
        "\"same …\" columns compare people found by both sources. The few differences "
        "are consistent with live Wikidata edits between the two fetches.\n")
    print(f"\nSaved {OUT_PATH.relative_to(s.ROOT)}")


if __name__ == "__main__":
    main()
